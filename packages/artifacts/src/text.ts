export function reportText(lang: "en" | "fr", key: keyof typeof TEXT, ...values: string[]): string {
  return plainTerm(lang,TEXT[key][lang === "fr" ? 1 : 0]).replace(/\{(\d+)\}/g, (_, n: string) => values[Number(n)] ?? "");
}

/** Translate only the system wording around a source; retain document names, quotes and a person's reason. */
export function reportSource(lang: "en" | "fr", source: string): string {
  if (lang === "en") return source;
  if (source === "Default accepted") return reportText(lang, "defaultAccepted");
  if (source === "Approved") return reportText(lang, "approved");
  if (source.startsWith("Entered by ")) return reportText(lang, "enteredBy", source.slice(11).replace(/^an analyst(?=:|$)/, reportText(lang, "anAnalyst")));
  return source.replace(/, labelled by a person$/, reportText(lang, "labelledByPerson"))
    .replace(/, converted from square metres \("(.*)"\)/, (_, raw: string) => reportText(lang, "convertedMetres", raw))
    .replace(/\bline (\d+)\b/g, "ligne $1");
}
